"""acceptable-v2 appendix material, generated from result JSON (no hand-typed numbers):
tab_gates (per-gate one-sided bounds), tab_manifest (per-run settings), tab_trainsizes (remedy training sets), A_prompts (verbatim prompts)."""
import json, os
R = "../exp/results"; D = "../exp/data/sit_train"
G = [("ix_can", "IX cancel."), ("imppres_truth", "IMPPRES true/false"), ("folio", "FOLIO"), ("gsm8k", "GSM8K")]
ROWS = [("1 Seed (route)", "Qwen3-8B", "selection_dev_Qwen3-8B.json", "seed_route"), ("", "", "selection_dev_Qwen3-8B.json", "think_full+sitroute"),
        ("2 Late check", "Qwen3-8B", "selection_dev_v2_Qwen3-8B.json", "late_sitcheck"), ("", "", "selection_dev_v2_Qwen3-8B.json", "late_neutral"),
        ("3 SFT", "Qwen3-8B", "selection_dev_D_q3.json", "SIT-train_selected"), ("", "", "selection_dev_D_q3.json", "control_unselected"),
        ("", "R1-0528", "selection_dev_D_r1.json", "SIT-train_selected"), ("", "", "selection_dev_D_r1.json", "control_unselected"),
        ("4 DPO", "Qwen3-8B", "selection_dev_E_q3.json", "dpo"), ("", "", "selection_dev_E_q3.json", "dpo_shuffled"),
        ("", "R1-0528", "selection_dev_E_r1.json", "dpo"), ("", "", "selection_dev_E_r1.json", "dpo_shuffled"),
        ("Task-aware instr.", "Qwen3-8B", "selection_dev_v2_Qwen3-8B.json", "think_full+taskaware")]
NAME = {"seed_route": "remedy", "think_full+sitroute": "control", "late_sitcheck": "remedy", "late_neutral": "control", "SIT-train_selected": "remedy",
        "control_unselected": "control", "dpo": "remedy", "dpo_shuffled": "control", "think_full+taskaware": "baseline"}
f = lambda x: f"{x:+.1f}".replace("-", "$-$") if abs(x) >= 0.05 else "0.0"
L = ["% GENERATED by tools/make_app_v2.py", "\\begin{table*}[t]", "  \\centering\\small",
     "  \\caption{Safety gates of every remedy on development items: paired difference to natural thinking (pp) and, in brackets, its one-sided 95\\% lower bound; a gate passes when the bound exceeds $-2$ (\\ding{55}: fails). $n$: items per gate.}",
     "  \\label{tab:gates}", "  \\begin{tabular}{@{}lll" + "r" * len(G) + "@{}}", "    \\toprule",
     "    Remedy & Model & Arm & " + " & ".join(g for _, g in G) + " \\\\", "    \\midrule"]
nrow = None
for name, mdl, fn, arm in ROWS:
    gd = json.load(open(f"{R}/M1/{fn}")).get("gates", {}).get(arm)
    if not gd: continue
    if name and len(L) > 9: L.append("    \\addlinespace[0.5mm]")
    cells = [f"{f(gd[g]['diff'])} [{f(gd[g]['lb'])}]" + ("\\,\\ding{55}" if gd[g]["lb"] <= -2 else "") for g, _ in G]
    nrow = [str(gd[g]["n"]) for g, _ in G]
    L.append(f"    {name} & {mdl} & {NAME[arm]} & " + " & ".join(cells) + " \\\\")
L += ["    \\midrule", "    \\multicolumn{3}{@{}l}{$n$} & " + " & ".join(nrow) + " \\\\", "    \\bottomrule", "  \\end{tabular}", "\\end{table*}"]
open("tables/tab_gates.tex", "w").write("\n".join(L) + "\n")
# manifest
M = json.load(open(f"{R}/MANIFEST/runs.json"))
L = ["% GENERATED by tools/make_app_v2.py", "\\begin{table}[t]", "  \\centering\\small",
     "  \\caption{Run settings per experiment block: models, items per model, decoding seeds, temperature and thinking cap (tokens).}",
     "  \\label{tab:manifest}", "  \\begin{tabular}{@{}lrrrrr@{}}", "    \\toprule", "    Block & Models & Items & Seeds & $T$ & Cap \\\\", "    \\midrule"]
for k, v in M.items():
    if not isinstance(v, dict) or not v.get("runs"): continue
    r = v["runs"][0]; s = r.get("sampling") if isinstance(r.get("sampling"), dict) else {}
    if r.get("n_items") is None: continue
    L.append(f"    \\texttt{{{k.upper()}}} & {len(v.get('models', []))} & {r['n_items']:,} & {len(r.get('seeds') or [])} & {s.get('temperature', 'API') or 'API'} & {s.get('cap') or '--'} \\\\".replace(",", "{,}"))
L += ["    \\bottomrule", "  \\end{tabular}", "\\end{table}"]
open("tables/tab_manifest.tex", "w").write("\n".join(L) + "\n")
# training sizes
L = ["% GENERATED by tools/make_app_v2.py", "\\begin{table}[t]", "  \\centering\\small",
     "  \\caption{Training sets of the trained remedies: traces per family (equal quota), and the share drawn from items the model answers correctly in only 1--3 of 4 samples.}",
     "  \\label{tab:trainsizes}", "  \\begin{tabular}{@{}llrr@{}}", "    \\toprule", "    Model & Family & Traces & Mixed share \\\\", "    \\midrule"]
for i, (mn, d) in enumerate([("Qwen3-8B", "Qwen3-8B"), ("R1-0528-Qwen3-8B", "DeepSeek-R1-0528-Qwen3-8B")]):
    p = f"{D}/{d}/stats_summary.json"
    if not os.path.exists(p): continue
    fam = json.load(open(p))["D_selected_control"]["families"]
    if i: L.append("    \\addlinespace[0.5mm]")
    for j, (fk, fv) in enumerate(fam.items()):
        L.append(f"    {mn if j == 0 else ''} & {fk} & {fv['N']:,} & {100 * fv['mixed_share_of_selected']:.1f}\\% \\\\".replace(",", "{,}"))
L += ["    \\bottomrule", "  \\end{tabular}", "\\end{table}"]
open("tables/tab_trainsizes.tex", "w").write("\n".join(L) + "\n")
# prompts
P = json.load(open(f"{R}/PROMPTS/verbatim.json"))
out = ["% GENERATED by tools/make_app_v2.py from exp/results/PROMPTS/verbatim.json", "\\section{Verbatim Prompts}", "\\label{app:prompts}",
       "Each block shows one fully rendered prompt per format or arm (user turn and, where the arm adds one, the assistant prefix), for one example item."]
for k, v in P.items():
    if k.startswith("_") or k.startswith("remedy_"): continue
    out.append(f"\\paragraph{{{k.replace('_', ' ').capitalize()}.}} {v.get('note', '') if isinstance(v, dict) else ''}".replace("_", "\\_").replace("#", "\\#").replace("%", "\\%"))
    body = (v.get("user") or v.get("text") or "") if isinstance(v, dict) else str(v)
    extra = [x for x in ("seed_sentence", "late_text") if isinstance(v, dict) and v.get(x)]
    for x in extra: body += f"\n[{x}] " + str(v[x])
    import textwrap
    wrapped = []
    for l in body.replace("\t", "  ").split("\n"):
        wrapped += textwrap.wrap(l, 50, subsequent_indent="  ", break_long_words=True, replace_whitespace=False) or [""]
    out += ["\\begin{footnotesize}", "\\begin{verbatim}"] + [w.replace("\\end{verbatim}", "\\end {verbatim}") for w in wrapped] + ["\\end{verbatim}", "\\end{footnotesize}"]
open("sections/A_prompts.tex", "w").write("\n".join(out) + "\n")
print("ok")
