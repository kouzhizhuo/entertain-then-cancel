"""Ablation of SIT on Qwen3-8B development items. Training-free rows from m1dev keys; trained rows fill from m1dev.qwen3-8b.v3.* when they land."""
import re
V = dict(re.findall(r'\\resdef\{([^}]+)\}\{([^}]*)\}', open("build/results_full.tex").read()))
ROWS = [(None, "Without training"),
        ("Natural thinking", "v2.nat"), ("Task-aware instruction (user turn)", "v2.taskaware"),
        ("Late check: entailment or speaker meaning?", "v2.sitcheck"), ("Late check: neutral", "v2.neutral"),
        ("Start-of-thinking seed (route)$^\\ast$", "v1.route"), (None, "Trained on own traces"),
        ("\\sit w/o trace selection (equal-data control)", "v3.control"), ("\\sit w/o family balance", "v3.nobal"),
        ("FULL", "v3.sit")]
COLS = ["speaker", "presup", "literal", "score"]
L = ["% GENERATED by tools/make_tab_ablation.py -- do not edit by hand.", "\\begin{table}[t]", "  \\centering\\small", "  \\caption{Ablation of \\sit on development items (Qwen3-8B): accuracy (\\%) by family; score is the mean of speaker and literal accuracy.}", "  \\label{tab:ablation}",
     "  \\setlength{\\tabcolsep}{4pt}", "  \\resizebox{\\columnwidth}{!}{%", "  \\begin{tabular}{@{}lrrrr@{}}", "    \\toprule",
     "    Arm & Speaker & Presup. & Literal & Score \\\\", "    \\midrule"]
for name, k in ROWS:
    if name is None:
        L += ["    \\midrule" if k == "Without training" else "    \\addlinespace[0.5mm]", f"    \\multicolumn{{5}}{{@{{}}l}}{{\\emph{{{k}}}}} \\\\"]; continue
    if name == "FULL":
        key = f"m1dev.qwen3-8b.{k}"
        cells = [f"\\res{{{key}.{c}.mean}}" if f"{key}.{c}.mean" in V else "\\runcell" for c in COLS]
        L += ["    \\midrule", "    \\ourrow \\textbf{\\sit (full)} & " + " & ".join(cells) + " \\\\"]; continue
    key = f"m1dev.qwen3-8b.{k}"
    cells = [f"\\res{{{key}.{c}.mean}}" if f"{key}.{c}.mean" in V else "\\runcell" for c in COLS]
    L.append(f"    {name} & " + " & ".join(cells) + " \\\\")
L += ["    \\bottomrule", "  \\end{tabular}}",
      "  \\par\\smallskip{\\footnotesize $^\\ast$From development run~1 (\\Cref{tab:m1dev}); all other rows share the same saved thoughts.\\par}", "\\end{table}"]
open("tables/tab_ablation.tex", "w").write("\n".join(L) + "\n"); print("wrote tables/tab_ablation.tex")
