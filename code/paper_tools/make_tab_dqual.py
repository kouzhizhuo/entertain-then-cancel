"""Development qualification of the trained variants (attempts 3-4), both models, from m1dev keys."""
import re
V = dict(re.findall(r'\\resdef\{([^}]+)\}\{([^}]*)\}', open("build/results_full.tex").read()))
MODELS = [("Qwen3-8B", "qwen3-8b"), ("DeepSeek-R1-0528-Qwen3-8B", "r1-0528")]
ARMS = [("Natural thinking", "d.nat"), ("SFT, unselected traces (control)", "d.control"), ("SFT, selected traces (\\sit)", "d.sit"),
        ("DPO, shuffled pairs (control)", "e.dposhuf"), ("DPO, correct vs.\\ incorrect (\\sit-DPO)", "e.dpo")]
COLS = ["speaker", "presup", "literal", "score", "tokfc"]
L = ["% GENERATED by tools/make_tab_dqual.py -- do not edit by hand.", "\\begin{table}[t]", "  \\centering\\small",
     "  \\caption{\\textbf{Tuning on the model's own traces does not beat its controls.} Development accuracy (\\%) by family, score and thinking tokens; \\ding{51}: passes all safety gates.}",
     "  \\label{tab:dqual}", "  \\setlength{\\tabcolsep}{3.5pt}", "  \\resizebox{\\columnwidth}{!}{%", "  \\begin{tabular}{@{}lrrrrrc@{}}", "    \\toprule",
     "    Arm & Speaker & Presup. & Literal & Score & Tokens & Gates \\\\"]
for i, (mn, m) in enumerate(MODELS):
    L += ["    \\midrule" if i == 0 else "    \\addlinespace[0.5mm]\\midrule", f"    \\multicolumn{{7}}{{@{{}}l}}{{\\textsc{{{mn}}}}} \\\\"]
    for name, k in ARMS:
        key = f"m1dev.{m}.{k}"
        if f"{key}.score.mean" not in V: continue
        cells = " & ".join(f"\\res{{{key}.{c}.mean}}" for c in COLS)
        pre = "\\ourrow " if k.endswith((".sit", ".dpo")) else ""
        L.append(f"    {pre}{name} & {cells} & \\ifdim\\rv{{{key}.gates.mean}}pt>0.5pt \\ding{{51}}\\else \\ding{{55}}\\fi \\\\")
L += ["    \\bottomrule", "  \\end{tabular}}", "\\end{table}"]
open("tables/tab_dqual.tex", "w").write("\n".join(L) + "\n"); print("wrote tables/tab_dqual.tex")
