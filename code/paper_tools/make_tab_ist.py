#!/usr/bin/env python3
"""Generate tables/tab_ist.tex from build/results_full.tex: token-matched seeds (E10) with their own off/nat rows,
prompted CoT (E8) and PragReST (E1S). Bold/underline = best/second among the thinking rows per column."""
import re
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
V = dict(re.findall(r'\\resdef\{([^}]*)\}\{([^}]*)\}', (ROOT / "build/results_full.tex").read_text()))
num = lambda k: float(V[k]) if k in V else None
COLS = [("qwen3-8b", "a3-quant.inf", "R"), ("qwen3-8b", "a3-conn.inf", "R"), ("qwen3-8b", "b2.yn", "acc"),
        ("qwen3-32b", "a3-quant.inf", "R"), ("qwen3-32b", "a3-conn.inf", "R"), ("qwen3-32b", "b2.yn", "acc")]
ROWS = [("No thinking (\\NT)", "e10", "off", False), ("Natural thinking (\\NAT)", "e10", "nat", True),
        ("Prompted CoT, thinking off$^{a}$", "e8", "cot", True), None,
        ("Neutral seed", "e10", "sneu", True), ("Logic seed", "e10", "slog", True), ("Intent seed (\\method)", "e10", "sint", True)]
rank = {}
for j, (m, st, met) in enumerate(COLS):
    vals = sorted([(num(f"{pre}.{m}.{st}.{c}.{met}.mean"), i) for i, r in enumerate(ROWS) if r and r[3]
                   for (_, pre, c, _) in [r] if num(f"{pre}.{m}.{st}.{c}.{met}.mean") is not None], reverse=True)
    for k, (_, i) in enumerate(vals[:2]): rank[(i, j)] = k
out = [r"% GENERATED by tools/make_tab_ist.py -- do not edit by hand.", r"\begin{table*}[t]", r"  \centering\small",
       r"  \setlength{\tabcolsep}{3pt}", r"  \begin{tabular}{@{}l ccc ccc@{}}", r"    \toprule",
       r"    & \multicolumn{3}{c}{\textbf{Qwen3-8B}} & \multicolumn{3}{c}{\textbf{Qwen3-32B}} \\",
       r"    \cmidrule(lr){2-4}\cmidrule(l){5-7}",
       r"    \textbf{Method} & \form{some}\hup & \form{or}\hup & LUDWIG\hup & \form{some}\hup & \form{or}\hup & LUDWIG\hup \\", r"    \midrule"]
for i, r in enumerate(ROWS):
    if r is None:
        out += [r"    \midrule", r"    \multicolumn{7}{@{}l}{\textit{Seed sentence opening the thinking trace (26 tokens each)}} \\"]; continue
    name, pre, c, _ = r; cells = []
    for j, (m, st, met) in enumerate(COLS):
        k = f"{pre}.{m}.{st}.{c}.{met}"
        if num(k + ".mean") is None: cells.append(r"\na"); continue
        cell = f"\\cellpm{{{pre}}}{{{m}.{st}.{c}.{met}}}"
        cell = {0: f"\\textbf{{{cell}}}", 1: f"\\underline{{{cell}}}"}.get(rank.get((i, j)), cell)
        cells.append(cell)
    out.append(f"    {name} & " + " & ".join(cells) + r" \\")
out += [r"    \midrule", r"    \multicolumn{7}{@{}l}{\textit{Training-time fix, same backbone \citep{park2026pragrest}}} \\",
        r"    PragReST-8B, \NAT & \cellpm{e1s}{pragrest-8b.a3-quant.inf.nat.R} & \cellpm{e1s}{pragrest-8b.a3-conn.inf.nat.R} & \cellpm{e1s}{pragrest-8b.b2.yn.nat.acc} & \na & \na & \na \\",
        r"    \bottomrule", r"  \end{tabular}",
        r"  \par\smallskip{\footnotesize Seeds run with natural thinking; $^{a}$from a separate run with the same settings. PragReST-8B is trained against literal readings \citep{park2026pragrest}.\par}",
        r"  \caption{\textbf{The intent seed restores more enrichment than length-matched control seeds.} Pragmatic reading and LUDWIG accuracy (\%); mean $\pm$ s.d.\ over seeds; \textbf{bold}/\underline{underlined}: best/second among thinking rows.}",
        r"  \label{tab:ist}", r"\end{table*}"]
(ROOT / "tables/tab_ist.tex").write_text("\n".join(out) + "\n"); print("wrote tab_ist")
