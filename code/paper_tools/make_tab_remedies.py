import re
V = dict(re.findall(r'\\resdef\{([^}]+)\}\{([^}]*)\}', open("build/results_full.tex").read()))
ROWS = [("Seed at start of thinking", "none", "Qwen3-8B", "qwen3-8b.v1", "route", "userroute"),
        ("Check before thinking ends", "none", "Qwen3-8B", "qwen3-8b.v2", "sitcheck", "neutral"),
        ("SFT on own correct traces", "SFT", "Qwen3-8B", "qwen3-8b.d", "sit", "control"),
        ("", "", "R1-0528-Qwen3-8B", "r1-0528.d", "sit", "control"),
        ("DPO, correct vs.\\ incorrect", "DPO", "Qwen3-8B", "qwen3-8b.e", "dpo", "dposhuf"),
        ("", "", "R1-0528-Qwen3-8B", "r1-0528.e", "dpo", "dposhuf"),
        ("Early-prefix ensemble$^\\dagger$", "none", "Qwen3-8B", "qwen3-8b.x", "x1", "x1w0"),
        ("", "", "R1-0528-Qwen3-8B", "r1-0528.x", "x1", "x1w0"),
        ("No-think blend$^\\dagger$", "none", "Qwen3-8B", "qwen3-8b.x", "x2", "x2w0"),
        ("", "", "R1-0528-Qwen3-8B", "r1-0528.x", "x2", "x2w0")]
L = ["% GENERATED by tools/make_tab_remedies.py -- do not edit by hand.", "\\begin{table}[t]", "  \\centering\\small",
     "  \\caption{\\textbf{No remedy passes its safety gates.} Development score (mean of speaker-meaning and literal accuracy, \\%) for natural thinking, the remedy and its control; speaker-meaning accuracy in gray.}",
     "  \\label{tab:remedies}", "  \\setlength{\\tabcolsep}{3pt}", "  \\resizebox{\\columnwidth}{!}{%", "  \\begin{tabular}{@{}lllrrrc@{}}", "    \\toprule",
     "    Remedy & Train & Model & Natural & Remedy & Control & Gates \\\\", "    \\midrule"]
def c(k, extra=True):
    s = f"\\res{{{k}.score.mean}}"
    return s + (f"\\,\\textcolor{{gray}}{{\\scriptsize \\res{{{k}.speaker.mean}}}}" if extra else "")
for i, (name, tr, mn, blk, arm, ctl) in enumerate(ROWS):
    b = "m1dev." + blk
    if f"{b}.{arm}.score.mean" not in V: continue
    if name and i: L.append("    \\addlinespace[0.5mm]")
    gate = f"\\ifdim\\rv{{{b}.{arm}.gates.mean}}pt>0.5pt \\ding{{51}}\\else \\ding{{55}}\\fi"
    L.append(f"    {name} & {tr} & {mn} & {c(b + '.nat')} & {c(b + '.' + arm)} & {c(b + '.' + ctl)} & {gate} \\\\")
L += ["    \\bottomrule", "  \\end{tabular}}",
      "  \\par\\smallskip{\\footnotesize Controls: same text in the user turn; neutral check; unselected traces; shuffled pairs" + ("; weight 0. $^\\dagger$Exploratory, not pre-registered" if any("x1" in l for l in L) else "") + ". Details: \\Cref{app:remedies}.\\par}",
      "\\end{table}"]
open("tables/tab_remedies.tex", "w").write("\n".join(L) + "\n"); print("wrote tables/tab_remedies.tex", sum(1 for l in L if '\\res{' in l), "rows")
